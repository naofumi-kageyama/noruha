            <h2 class="heading">それぞれが《円盤に乗る派》に入るまでの歴史</h2>

            <p class="speaker">下駄</p>
            <p class="speech">こんにちは。《円盤に乗る派》で俳優の日和下駄です。今回のゲストは畠山さんです。</p>

            <p class="speaker">畠山</p>
            <p class="speech">こんにちは。《円盤に乗る派》の畠山峻と申します。よろしくお願いします。</p>

            <p class="speaker">下駄</p>
            <p class="speech">今回は、《円盤に乗る派》に所属している俳優であるという共通点から話していきたいと思います。ぼくは去年30歳になったんですけど、年齢的には節目になるので、ぼくの中で団体との関係を見直すムードがあって。これから団体とどう付き合っていけばいいかみたいなことを、今も考えているんですけど。この辺りのことを踏まえて畠山さんと話しながら、クリアにしていきたいと思っています。</p>
            <p class="speech">あと、ぼくは歴史的な俳優になりたいんですけど、歴史に残っている俳優さんは小劇場の有名な団体にいた傾向が少なからずあるなと思って。転形劇場にいた大杉漣さんとか、状況劇場にいた小林薫さんとか。</p>
            <p class="speech">つまり、《円盤に乗る派》が歴史的な劇団になり、ぼくも歴史的な俳優になるというルートがありえそうと考えた時に、団体というものについて考えた方が良いなと思っていて。</p>

            <p class="speaker">畠山</p>
            <p class="speech">なるほど。</p>

            <p class="speaker">下駄</p>
            <p class="speech">その前提として、まずはぼくたち二人がなぜ《円盤に乗る派》にいるかということを話そうかなと。</p>
            <p class="speech">ぼくは、鳥取県に生まれて、横浜国立大学に進学しました。これは完璧に演劇をやるために出てきてます。</p>

            <p class="speaker">畠山</p>
            <p class="speech">あ、まじでそこからなんだ。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そうそう。鳥取から大学進学するとしたら関西の方が多くて、ぼくも最初はそう思ってたんだけど、地元の「鳥の劇場」*という劇場・劇団の芸術監督である中島諒人さんという方に、「演劇やるならどこ行くのがいいですかね？」と聞いたら「東京だろ」って言われて、関東の大学にきました。</p>

            <p class="footnote">鳥取県鳥取市鹿野町にある劇団であり劇場。毎年秋に国際演劇祭《鳥の演劇祭》を開催。<br>
              <a href="https://www.birdtheatre.org/birdtheatre/" target="_blank" rel="noopener noreferrer">https://www.birdtheatre.org/birdtheatre/</a>
            </p>

            <p class="speech">横浜国立大学はかつて唐十郎さんが教授をしてて、ぼくが進学した当時も「唐ゼミ」という劇団が継続していたので、演劇の風がビュンビュン吹いてるだろうと思ってたけど、実際行ってみるとそんな雰囲気じゃなかったんですね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">唐十郎がもともと好きだったの？</p>

            <p class="speaker">下駄</p>
            <p class="speech">いや、当時は寺山修司が一番好きだった。</p>

            <p class="speaker">畠山</p>
            <p class="speech">アングラの感じだったんだ。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そう、つかこうへいとかも好きだったね。当時は、学芸大学の佐藤信か、横浜国立大学の唐十郎にするかで進学先を迷ってたな。それで、横浜国立大学に進学したんだけど、先述の通り自分が想像してた感じとは違ったから、大学辞めようかなとか吹聴してた。そしたら、今は早稲田小劇場どらま館で制作をしている歌人の吉田恭大さん*に「せっかく入ったんだから卒業した方がいいよ」と止められて、ワークショップも紹介するからってことで、カゲヤマさんのワークショップを紹介してもらった。</p>

            <p class="footnote">鳥取県出身の歌人・舞台製作者。主な歌集に『フェイルセーフ』『光と私語』がある。</p>

            <p class="speaker">畠山</p>
            <p class="speech">あ、じゃあカゲヤマくんのお芝居を見てたわけじゃないけど受けに行ったんだ。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そう、受けに行った当時はさっぱりわかんなくて。多分、シュールリアリズムの影響を受けて、カゲヤマさんの中で、自動筆記が流行ってた時期なんじゃないかと思うけど。この空間を歩いて頭に思いついたことを言ってくださいみたいな指示をされたんだよね。それで、目の前にカーテンがあったから「カーテン、カーテン」って言ってたら「どう思いました？」って聞かれて、「カーテンがあったからカーテンって言いました」「そうですか」みたいに終わった。</p>
            <p class="speech">その後、ワークショップが終わって、カゲヤマさんと吉田さんとご飯食べてるときに、カゲヤマさんが今年の夏に利賀演劇人コンクールに出るから手伝ってくれる人を探してるんだよねって話になって。いまになったらわかるけど、利賀演劇人コンクールってそこまでお金が出ないから、本格的なスタッフさんを雇うと大変で、若い大学生とかに手伝ってもらった方がいいという話だったんだと思うけど、行ってみたいなと思って18歳のときに一緒に利賀村に行ったんです。</p>

            <p class="speaker">畠山</p>
            <p class="speech">結構時間が経った感じがしたけど、18歳までの話だったんだ。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そう、18歳だから12年前の話ですね。それから大学時代はカゲヤマさんの作品に出るみたいなことは全くなくて、カゲヤマさんの作品も『キリンの親/モッツォ』くらいしか観てなかったんだけど、ぼくが大学4年生のときにsons wo:最後の公演『流刑地エウロパ』に向けてワークショップオーディションをやりますというお知らせを見て。その時に、18歳の時に会ってここまであんまり交流はなかったけど、大学卒業するタイミングでカゲヤマさんの公演に出たらエモいんじゃないかと思った。歴史っぽいというか。</p>

            <p class="speaker">畠山</p>
            <p class="speech">やっぱり歴史化したいんだね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">だから、そのエピソードを書いてワークショップオーディションに応募したんだけど、やってみたら面白かったんだよね。その時は、「世界の意味が均等になるようにフラットに見る」みたいなことと、「文章を自分が捉えられる単位にして発語を繋げていく」ということをやってた。</p>
            <p class="speech">ちょっと話は戻るんだけど、ぼくは、現代口語演劇というものができなかったんです。テキストをただ言えばいい、という理論だと認識してるんだけど、ぼくは緊張しちゃって、書いてあることをそのまま読むみたいなことができなかった。でも環境的に現代口語の演技ができる俳優が人気の俳優としてたくさんいたから、その中でどうやったら勝てるんだろうかと大学時代にモヤモヤと考えていたんだけど、現代口語演劇ではない演技の方法がカゲヤマさんのワークショップでは示されていた。それでまあ無事にワークショップオーディションに受かって、『流刑地エウロパ』に出演することになった。</p>
            <p class="speech">その後、一年留年することになるんだけど、学生演劇シーンにいたわけではないから、大学を卒業した後にこのまま演劇を続けても何もないまま時が過ぎていくかもっていう危機感があった。それで、関係性もあり、その中で勢いもあって、一番興味があるのは、カゲヤマさんだなと思って、カゲヤマさんと一緒にやっていったら自分の存在感も示していけるんじゃないかなというなんとなく思ってたら、カゲヤマさんから『幸福な島の誕生』のオファーが来た。二回目も呼んでもらえるってことは、カゲヤマさんの印象も悪くないんだと思って、カゲヤマさんに「《円盤に乗る派》に就職させてください」って言ったら、お互いのビジョンを話そうとなり、お互いのビジョンに重なる部分があるねってなって入ることになった。</p>

            <p class="speaker">畠山</p>
            <p class="speech">なるほど。ぼくは自分のことを歴史化しようとしてないからあんまりうまくまとめられないんだけど……。</p>
            <p class="speech">ぼくは北海道札幌市出身で、サブカルとか音楽とか映画がすごく好きな男の子でした。高校の時はヒップホップとかも好きで、当時は今売れてる漢a.k.a.GAMIのMSCとか神奈川のSD JUNKSTAとか*が出てきた時期で、いろんな地方でクルーと呼ばれるようなコミュニティをつくって、PVとか撮ってる様子を見てかっこいいなと思ってた。自分は音楽がやれるわけでもないけど、でもやっぱり何かをやりたいなと思って、中学のときの学芸会でやった演劇とか面白かったなっていう思い出があって。あと、殿山泰司さんっていう俳優さんの本を読んだりしておもしろくて。とにかく何かをやりたいという気持ちのとっかかりとして俳優というものを選び、舞台芸術学院っていう俳優の学校を進路に選んだ。</p>

            <p class="footnote">MSC：ヒップホップMC・漢 a.k.a GAMIがリーダーとして、2000年に結成したヒップホップクルー。新宿を拠点に活動。<br>
              SD JUNKSTA：神奈川県相模原市のヒップホップ集団、SDP（Sag Down Posse）に所属しているグループ。
            </p>

            <p class="speaker">下駄</p>
            <p class="speech">演劇も結構見てたの？</p>

            <p class="speaker">畠山</p>
            <p class="speech">映画と音楽と本が大好きなだけで、演劇は全然見てない。でも中学のときに寺山修司の本をハマって読んでたんだけど、こんな本を読んでるような人間じゃいけない！と思って全部捨てたりしたね（笑）。でもそのときに演劇というものがあるんだ、くらいの認識はしてたかも。</p>

            <p class="speaker">下駄</p>
            <p class="speech">その感じから演劇の俳優をやるようになるというのはちょっと飛躍があるね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">そうだね、なんで俳優なのかとかはあんまり考えてなかったんだよね。だから俳優をやってる過程で、その良さみたいなのがわかってきたという順番かも。</p>
            <p class="speech">舞台芸術学院*は、志願書を蛍光ペンとかじゃない黒いペンで書けば受かるって学校見学で言われて、そこに2年間通ってました。座学というよりも実践という感じで、演出家の先生がいて1年間で上演を作るみたいな感じだった。作品としては割と硬派な感じだったんだけど、自分はあんまりうまいことできなくて。</p>

            <p class="footnote">東京都豊島区にある専門学校。俳優養成を目的とし、舞台芸術専門課程が設置されている。2026年3月での閉校を発表した。<br>
              <a href="https://www.bugei.ac.jp/" target="_blank" rel="noopener noreferrer">https://www.bugei.ac.jp/</a>
            </p>

            <p class="speaker">下駄</p>
            <p class="speech">役作りとかする感じだったの？</p>

            <p class="speaker">畠山</p>
            <p class="speech">いや、あんまり方法は教わってないんだよね。とりあえずやってみるみたいなスタイルだった。だから上手くなれる人は芽が出るんだけど、自分はとくに何もなく2年経って卒業して。</p>
            <p class="speech">卒業したら大体先輩の団体とかに出るんだけど、ぼくは1本くらい出ただけで特につながらず、でも自分は俳優として活動してるんだって思いながら、友達とBBQをやったりして日々を過ごしてました。その後、橋本清くん（現y/n）がやってたブルーノプロデュースという団体に呼ばれて出はじめたりして。</p>

            <p class="speaker">下駄</p>
            <p class="speech">あ、急に出てきたね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">これが歴史化できてないってことか……（笑）。</p>
            <p class="speech">キラリ⭐︎ふじみっていう劇場で市民劇の公募があって、パスカル・ランベールという演出家の作品に出ることになって。そのときに橋本くんが演出助手か何かで関わってて、そこで見て呼んでくれるようになった。ブルーノプロデュースは、ドキュメンタリーシリーズという作品で、台本も基本的にない状態で自分が普通に喋ってる状態をベースにしてやるというか、学校でやってた演技とも全然違ってた。ブルーノプロデュースの『くんちゃん』っていう作品に出た時のアフタートークにカゲヤマ君が来てて、その後に作品に出演しませんかって声がかかった。</p>
            <p class="speech">当時はさっきも出た、自動筆記っぽい作品というか、戯曲の言葉を真に言おうみたいなことに稽古で取り組んでて。文章が長くなればなるほど真意をもって言うことが困難になるというふうに僕はその意図を捉えてるんだけど、例えば「りんごを持ってる男が現れた」というテキストがあったら、「りんごを持ってる男が現れた」のままでは言えないけど、「りんご」までなら言えるみたいに考えて、単語を分断したあと音として繋げるみたいなことをやってた、だから当時は戯曲を全部単語帳に書いて覚えてたね。これが2013年、26歳ぐらいのときかな。</p>

            <p class="speaker">下駄</p>
            <p class="speech">ぼくがまだ鳥取にいるときだね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">そこからも活動は続いていくんだけど、そんなにたくさんは出てないから、徐々にカゲヤマくんの演劇に出てる割合が増えてきて、常連の客演みたいな感じでやってたんだよね。2020年に『おはようクラブ』っていう作品に出たあとに、下駄くんとカゲヤマくんに誘ってもらって入ったという感じですね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">当時ちょうど人を増やそうみたいな話をしていたタイミングでもあって、ぼくも誘おうっていいました。</p>

            <p class="speaker">畠山</p>
            <p class="speech">でも、誘われた時はセリフを覚えることとチラシを配ることくらいしかできないよ、ってハードルを下げに下げてた気がする（笑）</p>

            <p class="speaker">下駄</p>
            <p class="speech">当時の演劇界って、一人主宰のプロデュースユニット制が多かったじゃない。畠山さんもその流れで、団体に所属はしないでいたんだと思うけど、所属するってなってどう思った？</p>

            <p class="speaker">畠山</p>
            <p class="speech">あんまり深いことは考えてなかったけど、定期的に出れる機会を持てるのはいいことだなと思ってた。あと、カゲヤマくんが書く戯曲とか、演劇に対する考え方、要請する演技態みたいなものには基本的に共感してる部分があるし、一つの団体にいたらその場所で追求するみたいなこともできるなと思って。その部分に関しては一回も裏切られてないなと思うし。</p>

            <p class="speaker">下駄</p>
            <p class="speech">たしかに、そこは裏切られてないよね。</p>
          </section>

          <section>
            <h2 class="heading">《円盤に乗る派》に所属するメンバーとしての所感、これから二人はどうしてく？</h2>

            <p class="speaker">下駄</p>
            <p class="speech">もう少し最近になってからの話をすると、冒頭にも話した通り、30歳を控えるにつれ団体との関わり方をどうしていこうかなと考えるようになったんだよね。というのも、ぼくは俳優と並行して制作という仕事もするようになったことが関係していて。俳優は明確にやりたいことなんですけど、制作はぼくにとって、自分がやることで良くなることがあるからできる、みたいな部分的な「やりたさ」なんだよね。だから制作と一言で言ってもやることはたくさんあるし、全部をやりたいとは言えない部分がある。</p>

            <p class="speech">で、《円盤に乗る派》でも、部分的に制作業務をやっていったりしたんですけど、『NEO表現まつり』*のときにいよいよぼく自身も責任を持つ立場になりました。《円盤に乗る派》という団体の在り方を考えた時に、そうやってカゲヤマさん以外の人が責任を持つ立場になるということは、いいことだと思ってたんです。いいことっていうのは、団体としては、個々人でやりたいことがある人が集まって、主従関係があるわけではないという関係なので、ぼくが責任ある立場につくのは、そのコンセプトがわかりやすく提示できるだろうと思ったんです。でも、実際やってみると、カゲヤマさんとの仕事の仕方が全然違ってうまくいかなかったんですよ。</p>

            <p class="footnote">2023年〜2024年に東京都荒川区西尾久で行われた演劇祭。日和下駄がプロデュースを務めた。<br>
              <a href="https://noruba.net/" target="_blank" rel="noopener noreferrer">https://noruba.net/</a>
            </p>

            <p class="speaker">畠山</p>
            <p class="speech">そうだ、その話はよくしてたよね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そう、そのことがすごく残念で。なんとか一緒にやれる方法を探っていたんだけど、仕事の進め方は人格に結びついてるところがあるから、そこを変えるというのはお互いに無理がある。だから、《円盤に乗る派》での制作業務は一回辞めることにした。本当は全部辞めなくてもいいんだけど。</p>
            <p class="speech">逆に、俳優だけの関わりになると、構造上仕方ないことだとは思ってるんだけど、どうしても演出家と俳優の間に上下関係っぽいものが生まれてしまう。創作の場ではそうだけど、団体の人間としてはある種責任がもうちょっと分散されている状態を作れた方が、《円盤に乗る派》の宣言に対するぼくの解釈とも一致してバランスがいいのかなと考えていたんです。</p>
            <p class="speech">《円盤に乗る派》に入った最初の頃は、ぼくが演劇界で存在感を出していくために、ある種カゲヤマさんの力も借りてやってきたと思っていて、一方で団体に所属していることで仕事の傾向が限られるみたいなこともある気がして、いっそ団体を抜けた方が仕事の幅も広がるし、さっきの団体の在り方への解釈と自分の現実との不一致みたいなことにも悩まなくて済むかなと思ったりして。</p>
            <p class="speech">でも、2025年にオフィスマウンテンに出た時に相談してみたら、山縣太一さんから「辞めない方がいいよ」って言われて。</p>

            <p class="speaker">畠山</p>
            <p class="speech">なるほど。</p>

            <p class="speaker">下駄</p>
            <p class="speech">その言葉に何かを感じたの。そこから、作品作りにおいてはある種主従関係があるんだけど、それと別に団体とか関係なく、俳優として存在感を示すことで、なんとなくなんだけど団体においての個々の関係性がフラットにできるのではないか、と考えをシフトしていったんだよね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">なるほど、だから歴史に刻め！なんだ。</p>
            <p class="speech">でも下駄くんが続けて居てくれるのは嬉しいね。自分は《円盤に乗る派》において本当に何もしてないからさ、ちょっと引いた目線じゃないと話せないんだけど。自分は芝居をやりながら18年くらい続けてる仕事があって。その職場は結構同じようなメンバーである種のコミュニティみたいになってる。さっき話してた、働き方とか仕事の進め方が人格と結びついてるというのは本当にそうで、変えると言って変わるものじゃないじゃないですか。ぼくは、区分けがされてない仕事を見渡しながら取り組むみたいなことが苦手なんだけど、カゲヤマくんも下駄くんも、分化されてない仕事の大きな流れみたいなものの、流れが出始めてるところから全部できちゃうもんね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そうだね。ぼくもカゲヤマさんも、おそらく仕事のやり方も含めて考えたいんだよね。大きな流れとか塊をどう切り分けて、どう進めるかを考えたいというか。カゲヤマさんは事務的なこともできるけど、ぼくは事務に全く興味がなくて、切り分けにしか興味がないみたいなことはあるんだけど。逆にぼくは、畠山さんみたいに決められたことをやるみたいなことが苦手だから。</p>

            <p class="speaker">畠山</p>
            <p class="speech">その話でいうと、さっきの演技における演出家との主従関係みたいな話も、自分は全然抵抗感がないんだよね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">ぼくも稽古場にいるときはあんまり感じないんだけど、思想的に考えちゃうみたいなことなんだな。</p>

            <p class="speaker">畠山</p>
            <p class="speech">でも下駄くんの場合、その思想が演技に出てると思うよね。理性的な部分というか、そこが良さにも見えてるからな。</p>

            <p class="speaker">下駄</p>
            <p class="speech">ありがとう。逆に、理性的にしか演技ができないという悩みでもあるんだけどね。話してみると全然タイプが違う二人だよね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">タイプは違うけど、多分、外部からは結構同じ括りで見られてる気がするよね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">性格の違いみたいな部分が、具体的な演技の話にも還元されてる部分があるよね。さっき話した通り、ぼくはかなりコントローラブルにしてしまうところがある。</p>

            <p class="speaker">畠山</p>
            <p class="speech">ぼくはかなりアンコントローラブルにしてしまう部分が大きい。どんどん無意識に溜めていくみたいな感じだな。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そういう意味でも、畠山さんより上手になろう、みたいなことはあんまり思わないんだよね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">ぼくは上手いって言われたことないもんな（笑）、すごいって言ってもらえることはあるけど。</p>

            <p class="speaker">下駄</p>
            <p class="speech">ぼくの方が、上手いって言われた経験があるかもな。だから、畠山さんのアンコントローラブルな姿に憧れはある。</p>

            <p class="speaker">畠山</p>
            <p class="speech">でもやっぱり性質だよ、他のことができないんだ。</p>
            <p class="speech">そう。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そう言えるの、かっこいい。</p>

            <p class="speaker">畠山</p>
            <p class="speech">かっこ悪いよ（笑）。演劇に限らず仕事っていうのは再現可能じゃないといけないじゃない。そういう意味では、ぼくのやってることは仕事じゃない感じがする。ちょっと飛躍するけど、演技って、例えばエクセルが使えるみたいな職務経歴書に並ぶようなことじゃないと思っていて。技能的な話で言ったら、期限までにセリフを覚えられるとかそういうレベルの話でしかない。でも演技が上手いとか語られることがあって、そういう部分におもしろさがあるなと思っているんだけどね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">確かに。なんか演技が上手いってテレビドラマとか映画的なイメージというか、役があり会話ができるみたいなイメージで語れるけど、もっと広く考えられることだよなと思うよね。ところで、《円盤に乗る派》に関して、見た目のデザインとかは演出であるカゲヤマさんが整えてくれてるような気がするんだけど、そこについてはどう思う？さっきも《円盤に乗る派》としてぼくたち二人が揃ってるように見られると言ってたのは、そこら辺が関係している気もするんだけど。</p>

            <p class="speaker">畠山</p>
            <p class="speech">おぼろげな状態で揃えられてるって感じがするね。例えば、「8秒経ってでてくる」とか「手をここまで伸ばす」みたいな整え方もあると思うけど、カゲヤマくんは身振りとかに関しての指示をした後に「本質的なことじゃないから」ってよく言うじゃない。そのあたりは遊びとして捉えているような気がして、共有したり整えてる部分はおぼろげな状態だなと思う。</p>

            <p class="speaker">下駄</p>
            <p class="speech">たしかに、俳優の内面的な作業を重視してる分、かっちりしすぎないようにある種ファジーなものを共有していく感じがあるかもね。かっちりさせないという部分が《円盤に乗る派》の雰囲気に繋がっているというのは、不思議な話だね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">「8秒待つ」ということが目的化しちゃうことを避けてるという話でもあるかも。</p>

            <p class="speaker">下駄</p>
            <p class="speech">よく「一個になっちゃうとよくない」ということも言ってるもんね。</p>

            <p class="speaker">畠山</p>
            <p class="speech">このことはやっぱり特徴だよね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">もう少し客観的な目線だと、人形劇っぽいとか言われることもあるけど、そのことはどう思う？</p>

            <p class="speaker">畠山</p>
            <p class="speech">言われるね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">カゲヤマさんは演劇の原体験として人形劇があるみたいな話もよくするし、俳優が舞台上に平面的に配置される感じとか、動く／動かないがはっきりしてる感じとかもあるのかな。</p>

            <p class="speaker">畠山</p>
            <p class="speech">今聞いてて思ったけど、人形劇って操ってる人と操られてる人形がいると思うんだけど、《円盤に乗る派》は人形を動かしてる人がいないのに人形が動いてるみたいな感じは体感として近いかもしれない。最後まで糸が張り詰められることはないというか。</p>

            <p class="speaker">下駄</p>
            <p class="speech">なるほどね。だからぼくははっきりした演技ができないことに悩んでるんだな。</p>

            <p class="speaker">畠山</p>
            <p class="speech">それが《円盤に乗る派》の良さでもあるけど、そうなのかもね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">団体に所属してることのいいことと悪いことみたいな話もしたくて。</p>

            <p class="speaker">畠山</p>
            <p class="speech">そうだね、あるよねもちろん。</p>
            <p class="speech">去年オーディションを受けた中で、2箇所で同じ評価をされたことがあって。「ひろゆきみたいな喋り方をしますね」って言われたの。いわゆるドラマ喋りじゃなくて、ちょっと上から目線というか、語ってることと関係ないように喋るみたいなことなんだと思うけど。いわゆるオーディションとかを受けて、技術的に戦えるというか、機能的な演技ができる俳優だと自分のことは思ってないんだけど、少なからずこの演技になったことには《円盤に乗る派》の影響があるだろうなと思います。</p>
            <p class="speech">得たことは、セリフの捉え方が、必ずしも役の感情とかからでなくてもいいという前提を作れたことかな。言葉の捉え方を、未整理なまま身体に引きずり下ろすみたいなことができるようになった気がします。</p>

            <p class="speaker">下駄</p>
            <p class="speech">今の話の中に、ぼくが考えたいことがある気がした。さっきも言ったみたいに、ぼくはコントローラブルな演技をするタイプなんだけど。テキストを読むのだという態度から始めて、テキストから受けとったものがコントローラブルな枠から溢れ出すことを目指して基本的にはやっている。でもこれだと、枠の中身、つまり自分自身みたいなものを開示していく方向になると思ってる。でもお客さんはぼくの中身に興味ないだろうと思ってきて、興味を持ってもらうために、枠の形を変え始めたんだよね。それこそキャラクターっぽく見えるとか、人間っぽく見えるみたいなことを考えてるんだけど、いざ、その枠の形を変えることをやってみると意外とできるし、その枠の方にばっか集中しちゃうという事態が起きてる。これまで、枠を操作することもあんまりやってこなかったからおもしろいし、技術の向上も感じるんだけど、一方で、これまで扱ってきた未整理なものがあるという状態から離れてしまってるのが最近の課題だな。</p>

            <p class="speaker">畠山</p>
            <p class="speech">枠として役作りをする人とかがいるってことだろうね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そうだね。この未整理にどう向き合うかだなと思いました。</p>
