                        <p class="speech">「個」だと、こっちも気合い入れて見なきゃって感じになりますよね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">横田さんは、「秋の隕石2025東京」でオープニングプログラムの『現実の別の姿／別の現実の姿』の構成を担当してたと思うんですけど、それはどうでした？</p>

                        <p class="speaker">横田</p>
                        <p class="speech">出演者の方にはたくさんの不安を抱かせたと思います（笑）。</p>
                        <p class="speech">でも、呼びかけて、人を集めて、時間割をデザインして、声かけをして、みんなが心地よくいられる状態を作って、みたいなことをやってみて、これまで出演してきた団体の企画者たちはこんな大変なことをやってくれていたのかと感動しました。</p>
                        <p class="speech">自分が優柔不断だったので、全体をみんなで決めていった部分が大きくて。パフォーマーの人と同伴して、一緒に日々を過ごす中で、テキストを見たり喋ったりする人としていました。</p>

                        <h2 class="heading">それぞれの道を歩んできた3名、《円盤に乗る派》では何にトライし、今後どう進んでいく？</h2>

                        <p class="speaker">下駄</p>
                        <p class="speech">ここまでそれぞれのキャリアを振り返ってきたわけですが、《円盤に乗る派》の『「いまのところまだ存在しているわたしのたましいが……」』で再び共演することをもう一つの起点に、今回の《乗る派》のことと、今後のキャリアのことを話せたらと思います。</p>

                        <p class="speaker">深澤</p>
                        <p class="speech">《円盤に乗る派》は観客としても好きな団体だったので、出演できることが嬉しいです。でも嬉しいと同時に、何ができるんだろうとか、どういうことをしてるんだろうというのは、観てるだけではわからなかったので怖さもあって。でも稽古場は、質問しやすい空気があるし、開かれていて楽しいです。毎回の稽古で、自分がやってみたいことを持ち込める現場だなと思います。あと単純にテキストがおもしろい。そういえば、個々人の作業みたいなことをあんまり話さないですよね。テキストを介した話はするけど、個人の作業の追求を場で共有するみたいなことはなくて、でも《乗る派》の世界観が立ち上がっていてすごいなと思います。</p>
                        <p class="speech">これからは、今年は特に出演予定が決まっているとかはなくて。観劇することも演劇の中にいることだと思っているので、自分が出たい団体とか作品とかを発見していきたいなみたいな気持ちがあります。最近は、演劇以外のことで自分を耕したいなという気持ちがあって演劇を離れてたので、今年は演劇を耕す方向でやっていきたいなという気持ちです。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">横田さんはどうですか？《円盤に乗る派》の出演は二回目ですが。</p>

                        <p class="speaker">横田</p>
                        <p class="speech">もっともっと頑張らないといけないなと思ってます。ぼくの中でも実態がわからないところに足を突っ込みながら、お客さんにはその実態を見せていかないといけないので。自分はわちゃわちゃ系であえてテンパっちゃうみたいな方が得意技なんですけど、今回はテキストのこととか、舞台のことを考えるとその技は使えないなと思っていて。今回は物語になりたいと思います。このお話を上演にしていくという部分を出演者として頑張っていきたいです。</p>
                        <p class="speech">今後は、演技をしてるときの喜びを感じられる舞台に出たいですね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">ありがとうございます。ぼくは『仮想的な失調』のときに、主人公として巻き込まれるだけで、何もしないという役だったんです。これまでは公演ごとに個人的な課題を設定して、なにかをやるという方向でトライしてたんですけど、何もしないという方向が少し苦しくて。でもお客さんからの反応は良くて、つまりぼくがなにかをしないことで作品全体が見えやすくなったんだなと思うんです。でもぼくは《円盤に乗る派》のことをそういうことをやる場所だとは思ってないんですね。つまり、個人のことを追求する場所だと思ってる。やっぱり何かをやりたい、トライしたいという気持ちが強い。一方でお客さんにもおもしろいと思ってもらうためには作品全体のことを考えなきゃいけないという話もあって。今回の現場でも、この個人の作業と作品全体のことでのバッティングが自分の中で起きてて、考えていかなきゃいけないなと思いますね。本当は両方が成立するといいんですけど。あとは、やらないことをやるという矛盾を自分が受け入れられるかとか。</p>
                        <p class="speech">今後は、今日話してみて、全体性のある演劇に出てみたいなと思いました。これまでのポッドキャストでも自分が演劇シーンを横断的に活動するということを考えてきたんですけど、今までは「会話劇」みたいな言い方しかできなかったんですが、「全体性のある演劇」という新しい言い方が見つかってよかったです。</p>
                        <p class="speech">あとはやっぱり、ぼくはまさしく演技に興味があるようには見られてないんだなと思いました。ぼくの演技について熱く語りたくなるような演技をしていきたいなと思いましたね。</p>

                        <p class="speaker">横田</p>
                        <p class="speech">『仮想的な失調』ってQ太郎っていう役だっけ？ぼくはあの作品で、Q太郎が一番好き。劇の全体がQ太郎に向かってきてて、全体に狙われ続けてるみたいな感じがあった。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">ぼく自身はあの演技はあんまり好きじゃなかったけど、その方がぼくは魅力的に見えるみたいなことも考えていかないといけないんだなと思いました。</p>
                        <p class="speech">今日はお二人ともありがとうございました。</p>

