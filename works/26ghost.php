    <p class="p-works-description__copy">「……それはまァ、いろいろいうけど、けっきょく今の世の中のうごきは、すべて商品価値というものに解消していくわけでしょう、そういうもののなかに、はまりこんじゃった幽霊だな。つまり、実体のない純粋な商品のことですよ。……じつにナンセンスな世界だが、これが現実でね。」*</p>
    <div class="p-works-description__text c-content">
      <p>演劇プロジェクト《円盤に乗る派》は、2027年4月に座・高円寺1にて上演予定の新作公演に向けたクリエーションの一環として、安部公房の初期戯曲『幽霊はここにいる』（1958）の上演を試みる。</p>
      <p>『幽霊はここにいる』は、架空の町《北浜市》を舞台に、詐欺師の大庭と、戦友の幽霊が見えると語る青年・深川の出会いによって巻き起こる騒動を描いた、ナンセンスで不条理な喜劇だ。姿の見えない「幽霊」の存在によって加速度的に経済が動いていくさまは、資本主義社会への風刺であり、戦後という不安定な歴史的状況を映し出しているようでもある。しかしここで描かれているような幽霊は、2026年の現在、さらに強大かつ不気味に、さらにふてぶてしく、その存在感を示しているのではないだろうか？</p>
      <p>《円盤に乗る派》はこれまで、現代社会の中で疲弊した身体によりそう演劇作品を幾度となく上演してきた。本作から始まる一連のシリーズではそのテーマを真正面から取り上げる。いまの時代を生きる私たちの身体にまとわりつく幽霊の手触り、その冷たさを感じとっていただけたらと思う。</p>
      <p>「幽霊だけが異常なんで、あとはもうぜんぜん異常でない――ということが異常なわけで……もう、笑うしかない世界だ。」*</p>
      <p class="mt-8"><small>*「稽古場にて――安部公房・千田是也両氏にきく」（『安部公房全集008』（1998年、新潮社）収録）より</small></p>
    </div>
    <div class="p-works__additional-content c-white-area c-content">
        <h3>安部公房について</h3>
        <p>1924年東京生まれ。満州国奉天（現・瀋陽市）にて育つ。東京帝国大学医学部に留学するが、一時帰郷中に敗戦を迎え、引き揚げまでの混乱期に医学生ながら医療班に従事、大量の死者と直面する。引き揚げ後は大学に復学し卒業するが、生涯医師になることはなかった。1948年、『終りし道の標べに』で小説家デビュー。1951年 に短篇「壁 - S・カルマ氏の犯罪」で芥川賞を受賞。同時期に日本共産党に入党する（後に除名）。</p>
        <p>その後は小説のみならず、演劇、映画シナリオ、ラジオドラマやテレビドラマのシナリオ・企画・演出など、メディアを横断して活躍。1973年には自身の演劇集団「安部公房スタジオ」を発足させ、西武流通グループ（後のセゾングループ）代表・堤清二の後援によって西武劇場（後のPARCO劇場）を拠点に活動を行った。
        海外からの評価も高く、ノーベル賞にもっとも近い作家と言われたが、1993年に68歳にて没した。</p>
        <p>代表作として、小説に『砂の女』、『燃えつきた地図』、『箱男』、戯曲に『友達』、『緑色のストッキング』など。</p>
    </div>
