      <p><strong>〈乗る派クラブとは〉</strong></p>
      <p>2024年に「円盤に乗る派」から派生して立ち上げられたチーム。「乗る派」の作品を忘れがたいと思う有志が「公式ファンクラブ」として、「乗る派」の作品をいろいろな角度から楽しむための活動を行う。現メンバーは江尻悠介（編集者）、小澤みゆき（作家・編集者）、中村みなみ（舞台制作）の3名。</p>
      <p>江尻悠介<br /><span style="font-weight: 400;">編集者。大学で建築を学び、アートプロジェクトのコーディネーターを経て、現在は出版社に勤めるかたわら、ZINEをつくったり読書会を開いたりしている。</span>過去のプロジェクトに、「アワーライブラリー」（東京芸術祭、2021-22）など。</p>
      <p>小澤みゆき<br />作家・編集者。編著に『かわいいウルフ』、『海響一号 大恋愛』。笠井康平とのユニット「作家の手帖」としても活動し、2024年にはヴァージニア・ウルフ『灯台へ』日本初訳（葛川篤訳）の単行本を制作。</p>
      <p>中村みなみ<br />舞台制作。長島確のつくりかた研究所、マレビトの会制作部を経て、趣向、BEBERICA theatre companyなどの公演制作や、北千住BUoYの劇場運営に携わってきた。現在は無所属。</p>
