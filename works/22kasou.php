        <h2 class="mb-[60px]">
          「仮想的な失調」について<br>
          松田正隆（劇作家・演出家）
        </h2>
        <div class="[&_p]:my-[1em] [&_p:first-child]:mt-0 [&_p:last-child]:mb-0 [&_p]:text-base">
          <p>
            &ensp;&ensp;先日、ずいぶん久しぶりに故郷にかえった。母に会わなければと思い、兄と一緒に母の入所している高齢者施設を訪ねた。母は今年で95歳になる。感染症対策のために、施設内にいる母とは玄関先からオンラインでの面会となった。タブレットの画面を通してではあるが、何年ぶりかに会う母は元気そうに見えた。私は自分のことを「正隆」だと名乗ったが、母は、これは正隆ではないと言った。正隆はこんなジイさまではない、と。兄のことは、認識できていたが、私のことはわからなかった。面会のあいだ一貫して私の顔は「正隆」だと認知してもらえなかった。まあ、無理もないのかな、もうすぐ還暦の私だし、白髪あたまの長髪だし、髭も生えていたので、誰だかわからなかったのだろう。とくに悲しいという気持ちもなかったが、いい気分もしなかった。母に自分を認知されない経験というのははじめてのことだったので、これはいったいどういうことなのかと考えてみようと思った。</p>
          <p>
            &ensp;&ensp;息子である「正隆」という名前の人物像は依然として母のなかにはあって、「正隆」とその像の存在は確かにあるが、それと私の、この顔・この身体が一致しないというわけなのだ。だから、今の母にとって私は息子の名前を語る変なジイさまってことになっている。</p>
          <p>
            &ensp;&ensp;母親から「正隆」であることを否定された男の顔は誰なのだろう。それは得体の知れない人物である。私は、画面越しではあるが、母に対して気の毒なことをしている気がして、そういう意味では悲しくなってきた。彼女に向かって「正隆」と名乗る男は正隆ではないのだから、私のせいではないにしろ、「正隆」を名乗れば名乗るほどかわいそうなことをしているような気がする。会いに行かなければよかった。</p>
          <p>
            &ensp;&ensp;とは言え、実の息子なのだし、顔を見せないで東京に帰るのも悪い気がして、母の面倒を見ている兄も会って行けと言うので顔を出さざるをえなかった。それにしても、母親の前の、この私は誰なのか、というなんとも変な感じは拭えない。</p>
          <p>
            &ensp;&ensp;息子とは思えない人物が急に訪ねて来て、息子の名前を語ること。そして、それを息子ではないと否定したときに、息子の存在はまったくそこにないというわけではない。そこにある顔と身体は息子ではないが、そこにとりあえず何らかの顔と身体は現前していて、息子の名前を語っているということ自体で、その顔と身体は息子に紐づいてしまう。否定的にではあるが、その違うという否定性によって、息子はいま、ここではないどこかに存在してしまう。そこにある顔と身体が息子には思えないのに、私が息子の名前を語るものだから、えー、でも、これは息子には思えないな、という感じで息子じゃないと言えば言うほど、息子っぽさが、いま、ここにある身体とは違うどこかに張り付いてしまう。母の前で、私が、おかしな感覚に陥ったのは、私のほうからすれば、私は普通に「正隆」を名乗ってるのに、自分の母がそれを否定するからで、ああ、母に認知されないのだったら、もうそれは仕方のないことなのだなと思ったのと同時に、この「正隆」を名乗る人物（もちろん私のことだけど）」は、母にはどのように見えているのだろうかという不可思議さ（というか不気味さだろうか）だった。</p>
          <p>
            &ensp;&ensp;つまり、「正隆」という名前を名乗っても、自分の息子の正隆には思えない人物は、いったい誰として母の前にいるのか、ということがなんとも不思議（というか気色悪さと言えばいいのだろうか）に思えたのだ。これは例えば、ある人物を見かけて、それを誰だと思い出せないときの経験に近いのか。いや、「見覚えがあるのに誰なのか名前を思い出せない」というのと、「見覚えがないのに知っている人物の名前を名乗ってくる」のとでは、ちょっと違うのかもしれない。</p>
          <p>
            &ensp;&ensp;このようにして、親しいと思っていた人物が、唐突に自分のことを認識してくれない場面に出くわすと戸惑わざるをえない。再認されるべき自分の存在が、そうはならないというときに、自分の顔や身体は異様なものとして出現してくる。そして、名づけられる前に、この身体が現前（存在）していたのだということがあらわになる。自分がどういう立場なのか、なんなのか、わからなくても、この身体はこの現実に密着して当然のように「ある」ものなのだ。</p>
          <p>
            &ensp;&ensp;カゲヤマ気象台の戯曲『仮想的な失調』において提示されているのは、そのような「再認の失調」からの回復についての劇である。名前を失った(というか、盗られた)、ただ単に存在するとしか言いようのない身体が次第にチューニングされてゆき、その身体に、ある人物の罪と怨みの報いが炙り出されて劇は終わる。チューニングと書いたが、ふとコンビニに行って自分のことが改めて誰なのか、わかってしまうみたいな感じである。ちょっと気を失っていたけれど、コンビニの前で気がついたら、自分が戻って来たような。そうなったらなったで、その調子で生きていくしかない。</p>
          <p>
            &ensp;&ensp;それを、「物心が憑く」と言い表してもいいのかもしれない。現代に生きる人々がいくつものメディアとデバイスを乗りこなしてゆく主体を維持しているとしたら、そこでも複数の「物心」が憑いているはずなのだった。いま、この場ではこのようにふるまおうか、というように物心が身体に憑く。いや、能動的にこんな感じの物心で行こうという意識的な物心の獲得ではなく、物心には受動的に憑かれているのかもしれない。</p>
          <p>
            &ensp;&ensp;考えてみれば、俳優も物心が憑くようにして、いくつもの「役」を生きている。「役」＝「登場人物」が物語を探すようにして、あるいは、物語が「役」＝「登場人物」を求めるようにして、「登場人物」と「物語」は出会う。「物心が憑く」ということは、憑くべき「物語に参入する」ことである。因果応報の世界観に溶け込むことである。「再認の失調」から回復することは「物心」が憑いて物語の重心を獲得することである。その人物に物心が憑くと物語が生まれる。あるいは、物語に襲われる。９太郎は名取川の上でヒラオカくんの霊に取り憑かれた。</p>
          <p>
            &ensp;&ensp;物語の重心の発生には、物心が憑き、その憑くべき物語上の「役」と身体が不可分になる必要がある。「役」に身体が適応するためには、その「役」と「身体」との調整（チューニング）が必要で、それがうまくいくと物語上の「役」を上手に生きることができるようになる。</p>
          <p>
            &ensp;&ensp;それでは、「物心が身体に憑くこと」と「再認の失調によって身体があらわになること」は、どのような関係にあるのか。</p>
          <p>
            &ensp;&ensp;私たちは思い起こせば、いつの間にやら自我に目覚めていたし、その自我によって、この世界を認識して来た。自我が突如として機能しなくなったときに、再認の失調が起こる。その再認の失調からの回復は、物心が憑いてなされると先ほどは書いたが、それは、この身体が生まれて私たちに物心がついたことをなぞっているようなことであり、物心というのは自我に近いのだろうか。自我には領域があって、自我を失い、物心がその領域を満たす。つまり、自我という領域が容器のような空間で、そこに物心が入り込んで来て、自我と物心の容量の増減があるというような感じなのだろうか。それとも、デジタルに物心は自我に張り付いて、自我もたくさんの物心のうちの一つになるような感じで一瞬にして消え、物心に取り憑かれたり、自我が取り払われたりするのだろうか。そのあたりの仕組みはよくわからないが、いずれにせよ、自我と物心は区別がつかなくなる。</p>
          <p>
            &ensp;&ensp;自我の機能が失われ「再認の失調」によって、物心に取り憑かれるスキが生まれて、何らかのモノに憑かれることで復調し、回復がなされるとき、もうすでに物語にも取り込まれている。しかし、再認の失調を契機として、憑き物に憑かれることを回避することはできないか。あるいは、そんな一瞬にして起こる「憑く」「憑かれる」という出来事の速度を緩やかにすることはできないのだろうか。「再認の失調」の状況がそのままで先延ばしにされるようなことが起きないのだろうか。コンビニの前で、何でもない身体が９太郎に目覚めていく時間の緩衝地帯が持続するようなことが到来しないのだろうか。私が、私を認知してくれなかった母の前で感じたのも、そういう経験だった。私は私の身体のままで母の前では異様なジイさまだった。</p>
          <p>
            &ensp;&ensp;いま・ここにある身体は誰なのか。その問いに即座に答えを出せない時に、思考はその状況からの促しを受けている。それは、未知なる経験である。その経験を肯定的に価値づけることが演劇に求められているのではないか。演劇は物語を語り出す場ではあるが、そうであるがゆえに、物語に入り込めない身体が出現する場でもあるはずなのだ。</p>
          <p>
            &ensp;&ensp;そのことが再認の失調を契機として起こるというだけでは、やはり不十分だろう。ある一つの表現の事例を提示して、このエッセイを終えたい。</p>
          <p>
            &ensp;&ensp;オランダの写真家リネケ・ダイクストラのポートレイトがもたらすイメージは、それを見る者に何とも言えない感覚をつきつけて来る。たとえば、誰なのかわからない人物（ポーランドの娘）が水着姿で海辺を背景にして、こちらを眼差して立っている写真がそうである。そのイメージにつて、ジャック・ランシエールは「物思いにふけるイメージ」と呼び、次のように述べる。</p>
          <p class="mt-[2em]! mb-[2em]! ml-[2em] mr-0">
            &ensp;&ensp;物思いにふけるイメージとは、思考されていない思考を秘めたイメージである。つまりそのイメージを生み出した者の意図に帰着させることのできない思考、そしてそのイメージを何か特定の対象に結びつけることなく見る者に対して効果を及ぼす思考を秘めたイメージである。だとすれば、物思いにふける性格は、能動的であることと受動的であることの間のどちらとも定まらない状態を指し示すこととなろう」（ジャック・ランシエール/梶田裕訳「物思いにふけるイメージ」『解放された観客』法政大学出版局p139）</p>
          <p>
            &ensp;&ensp;イメージが物思いにふけるというのは、考えてみれば、奇妙な言い方で、普通イメージは思考するのではなく、思考の対象とみなされるのだが、「物思いにふけるイメージ」にはそのような思考の起点とその対象の関係を無効にする効果があると言うのである。そのイメージは、つまり、身体のありようを未規定性にとどまらせる効果を生んでいる。その効果は、再認に失調したままの身体が物語のさなかにとどまる可能性へと展開しうるのではないか。</p>
          <p>
            &ensp;&ensp;ダイクストラの写真は、身元の不確かな個人の連作によって構成されている。</p>
          <p class="mt-[2em]! mb-[2em]! ml-[2em] mr-0">
            &ensp;&ensp;これらはありきたりで、表現力に乏しい存在だが、そのせいで、ある種の距離感を纏い、ある種の神秘さを帯びている。この神秘さは美術館を満たしている肖像画の神秘さに似ている。これらの肖像画の描く人物は、かつては誰だかわかるものだったが、今のわれわれには無名の誰かになってしまったからだ。（同p140）</p>
          <p>
            &ensp;&ensp;無名の誰かになること。その無名の誰かは、かつて名前を持った物語のなかの誰かだった。そして今、その人は名前を失い誰かのままだ。それでも、その誰かのままで、その人は神秘的である。むしろ、無名ゆえにそうなのかもしれない。「物思いにふけるイメージ」の渦中にあれば物心（私は誰であり何をした/する人物なのかを知る心）に憑かれるスキはない。その人は物心の憑きようのない距離感を纏っているからだ。その「ある種の距離感」というバッファがあることで、物心にも幽霊にも憑かれることなく、私たちのいる現在の物語を生きていくことができる。そのとき、物語の重心さえも取り払われ、その場は軽味を帯びるのではないかと思われるのである。</p>
