<section class="p-works__section">
  <div class="p-works-description">
    <p class="p-works-description__copy">誰しもが「都市」を内に抱えた21世紀に、如月小春の言葉はいかに響くか？</p>
    <div class="p-works-description__text c-content next-description">
      <p>『MORAL』は1984年から1986年にかけて、如月小春の主宰する集団「NOISE」によって形を変えながら上演された作品です。断片的なイメージ、ぎくしゃくとした発話や身体、モニターを用いた映像の多用など、当時の先鋭的な表現が詰め込まれたこの作品は、それまでの演劇とは全く異なるパフォーマンスとして、当時の人々に衝撃をもって受け取られました。</p>
      <p>『MORAL』という作品からは、「消費社会」や「都市」といったテーマを読み取ることができます。事実、如月小春自身もこの作品を通じて「消費社会の身体」を追求したと語っています。ここで言われる「都市」や「消費社会の身体」という概念は、21世紀における現在においても未だ重要なトピックと言えます。スマートフォンの普及によってインターネットがあらゆる場所に偏在する、グローバル化以後の世界において、「都市」的なものはフラットに世界全体を覆いつつ、我々の身体の中にも染み付いています。</p>
      <p>「都市」に、「消費社会」の中に生きながら、同時に複雑さや矛盾も抱えた「個」でもある身体を暴き立てるためのきっかけとして、『MORAL』という戯曲の言葉たちは作用します。豊饒なイメージも深い人物造形もなく、単純なセンテンスで綴られた『MORAL』の言葉は、今の時代を生きる出演者たち、または上演の場に立ち会う観客のみなさんの身体に、どのように響くでしょうか。</p>
      <p>舞台に立つのは、主に一般公募によって集められたメンバーたち。約2ヶ月のワークショップを通じ、ひたすら戯曲の言葉と自分の声に向きあいながらパフォーマンスを制作します。そこには表面を繕われた見世物ではなく、多種多様の真摯な声が響きあう、特別な空間が立ち現れるでしょう。</p>
      <p>2022年の秋のごくわずかな瞬間、会場に居あわせた全員の間で、『MORAL』の言葉の乱反射が起きることを期待します。</p>
