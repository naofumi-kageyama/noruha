            <p class="speech">今このやり方で進んでいて、明確にいいところがある。作品として立ち上げる方法そのものを稽古で探っていく演劇の場合って、稽古中に演出家含めてみんな悩んでしまって前に進んでいる感じがないみたいなことがあるんですけど、今回の稽古の手法は進み続けるしかない手法なので、実際に進んでいるかはさておき進んでいることにはなるので非常におもしろいです。</p>
            <p class="speech">さっきもカゲヤマさんが話していたけど、特にステップ2は、俳優に委ねる部分が大きいなと思っています。《乗る派》にこれまで参加してきた体感を振り返ってみるとだんだんと俳優に委ねる部分が増えてきてる気がする。もともとカゲヤマさんは、具体的な作業を伝えるというより、緩やかな考え方みたいなものを共有して俳優に任せる感じだったけど、それがさらに進んだなというか、より緩やかになったというか。</p>
            <p class="speech">このステップが取り入れられたことは、子どもが生まれたこととも関係してるのかなと想像していて。具体的には俳優に任せられる領域を増やすことでカゲヤマさんが稽古を休めるみたいな話だと思うし、一方でカゲヤマさんの演劇観が発展したのかなとも思うんだけど。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうですね。確かに子どもが生まれたからというのは、ある種現実的な理由としてあるんですけど、状況によって仕方なくそれを選択してるというのは作家としては許しがたいという気持ちもあって。だから、実際このやり方をやってみたくて選択してると思うんですよね。</p>
            <p class="speech">前の新作が2023年にこまばアゴラ劇場でやった『幸福な島の夜』という作品なんですけど、その時の稽古でちょっと難しかった部分があって。説明をするんだけどうまく伝わらないなみたいな局面があった。その時に、俳優の言葉と演出家の言葉を同じレイヤーに揃えるのは無理なんじゃないかって思った。近寄ることはできるけど超えられない一線があるというか。しかも俳優も人によって全然違うから、人によって言葉を変えていく必要があるけど、完全に言葉を揃えていくということは無理なんだなという。</p>

            <p class="speaker">下駄</p>
            <p class="speech">稽古場で他の人に言ってることとか聞こえちゃうしね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">完全に1人ずつに話すわけじゃないから、演出家の言葉は演出の言葉として際立ってしまう状況を考えると、演出としては区切りを引いて、その先は俳優各々のチャレンジに任せていく方が、関係性としては健全なのかなと思って。</p>

            <p class="speaker">下駄</p>
            <p class="speech">《乗る派》は、基本的にすごい普通のことをやろうとしてるけど、普通のことを本当にやろうとするとちょっと変な形になっちゃってるみたいな感じだなと思っていて。初歩的なところに帰ってきて、そのことを本当にやろうとするというか。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">確かに、初歩にちゃんとたどり着いた方がいいみたいなことはある。</p>

            <p class="speaker">下駄</p>
            <p class="speech">やり方を発明してるなと思う。そういう部分にもつながるけど、《乗る派》は生活と演劇のシームレスな関係みたいなことも考えているから、子育ての影響みたいなことも起きているんだろうか？ と気になったのかもしれない。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">確かにそういう意味では、生活スタイルが変わって、ぼく自身の劇場に対する考え方が変わってるかもしれない。でもあんまりポジティブな感じでもないかな。前までは演劇を観てその周辺でご飯を食べたりお酒飲んだりしてたけど、そういう余白はなくなってきてる。だから逆にわざわざ劇場に行く良さみたいなのを回復したいとは思ってるかもしれない。</p>

            <p class="speaker">下駄</p>
            <p class="speech">生活者としてってことだよね。今聞いていて、生活者の視点で生活と演劇を見るときと、演劇作家の視点で生活と演劇を見るときで、それぞれが全然違う形をしてるのかなと思った。だから演劇作家のカゲヤマ気象台としては、生活と演劇を別に考えたいけど、生活者の1人としては繋がってるんだなというか。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうですね。自分は物事を考える時に割と切り替えをしてる。だから、育児をやっているときは子どものことを考えていて、作家の自分とは分かれてるみたいな感じだと思います。</p>

            <p class="speaker">下駄</p>
            <p class="speech">さっき『幸福な島の夜』でうまくいかなかった部分があったと話していたけど、ぼくの視点から見てると、オファーする俳優のレンジが広がってきているのかなと思った。それまでは、《乗る派》の興味関心と近そうな人とやっていた印象があるけど、規模が大きくなるにつれてオファーの幅が広がって、より多様な人と演劇をつくる方法を模索してる感じがある。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうだね。とはいえ、関心が近いと思ってた人も意外と考えてることが全然違ったりするじゃないですか。ある程度なんか話し合えてるように見えたりとか、共有できてるように見えてたりとかしても、意外とここは違うなという部分が見えてくる。その辺がよりミクロに見えてくようになったっていう感じも結構あるかな。</p>
          </section>

          <section>
            <h2 class="heading">《乗る派》、カゲヤマ気象台、そして日和下駄はこれからどう活動していく……？</h2>

            <p class="speaker">下駄</p>
            <p class="speech">様々な部分で変化が起きていたり、起きていなかったりしていると思うんだけど、これから子どもが成長していくことも見据えると、カゲヤマさんと演劇の関係は変化していくだろうし、それに伴って《乗る派》は変化していく気がしていて。これからカゲヤマ気象台として演劇活動をしていくこととか、《乗る派》はどういうことを目指していくのかを聞けたら。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">具体的な話をすると、引っ越す可能性があるんです。今住んでいるところが狭くなってきたらもうすこし広いところに引っ越そうってなると、やっぱり都内は難しいみたいな可能性が出てくるなと思っていて。そうなると必然的にフットワークは重たくなってくるというか、生活感がより増すんじゃないかなとは思います。</p>

            <p class="speaker">下駄</p>
            <p class="speech">演劇作家としてというよりは、まさしく生活者としての生活ってことですよね。それこそ、週末は郊外のイオンモールに行ったりとか。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうそうそうそう。そうなってきたら、その状況の中で、どう活動を続けていくかという話にはなってくると思う。あと、子どもが演劇というものを認識し始めたら、やっぱり観て欲しいなと思ってる。稽古場にもきて欲しいとかは思う。でも、それらの具体的な変化が、どう形に繋がってくるかはまだわかんないかな。例えば郊外的な行動パターンになるとかはあるかもしれないけど。</p>

            <p class="speaker">下駄</p>
            <p class="speech">郊外的な創作パターンって何？</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">週末だけ稽古するとかなのかな。</p>

            <p class="speaker">下駄</p>
            <p class="speech">でも、なんか分かってきたぞ。23区に住んでるサブカル文化人としての演劇の関わり方ではなく、23区外に住んでいる文化人のあり方みたいなことか。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうね。ほんとはね、『HOSONO HOUSE*』みたいなのがいいんだけどね。</p>

            <p class="footnote">細野晴臣のソロ・デビュー作。埼玉県狭山市にあった細野晴臣の自宅でレコーディングされた。</p>

            <p class="speaker">下駄</p>
            <p class="speech">逆に子どもとか関係なく考えてることもある？《乗る派》の今後として。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうですね。一つあるのは、劇作家という自認に対してもうちょっと自覚的に踏み込めるんじゃないかなとは思う。戯曲っていうものをちゃんと研究したいし、戯曲の発信の仕方とかにも取り組んでいきたい。これは自分の意向としてやりたいことでもあるし、そこをもっと掘り下げないとこれから劇作家としてサバイブしていきないんじゃないかとも思ってる。</p>

            <p class="speaker">下駄</p>
            <p class="speech">過去の戯曲研究みたいなこととかもするってこと？</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">戯曲の持ってる価値みたいなものっていうのを、演劇とかに関連する人は漠然と抱いてると思うんだけど、もうちょっとはっきりした形で、戯曲を読むとこういういいことがあるんだみたいな、こういうおもしろさがあるんだみたいなことを掘り下げるというか。</p>

            <p class="speaker">下駄</p>
            <p class="speech">自分にとっても社会にとってもってことか。カゲヤマさんは自己認識として劇作家の自認が強いんだよね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">もちろん既存の戯曲を上演したいっていう、演出家としてやりたいみたいな欲望も持ち合わせているから、自作の上演しかしたくないみたいなことではないんだけど。あと今は、既存の小説とか、古典文学の舞台化をやってみたい。</p>

            <p class="speaker">下駄</p>
            <p class="speech">それは演出家として？劇作家として？</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">どっちもかな。そもそも私は、根源的ないい作品をやりたいわけです。だから、古典文学の舞台化とかでいい作品になるのではないかという。ちょっと前に金曜ロードショーで『かぐや姫の物語』を見たことが影響してる可能性は否めないんだけど（笑）。</p>

            <p class="speaker">下駄</p>
            <p class="speech">劇作家としての自認があるカゲヤマさんにとって、演出ってなんなの？</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">戯曲の価値の話に繋がってくると思うんだけど、戯曲を読むっていう体験は、ただ文字の意味を汲んで理解してくみたいなことだけではないと思うんです。もっと広くいろんなことが起こる。戯曲によってこんないろんなことが起こるんだみたいなことを、演出なり上演という場によって、立ち上がるみたいなことを目指したい。</p>

            <p class="speaker">下駄</p>
            <p class="speech">自分が書いた、あるいは他の人が書いた戯曲が持ってる価値みたいなものを発揮するために、演出したりとか、舞台をやったりしてる部分もあるということ？</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">そうは言ったんだけど、それだけでもないような気がする……。</p>

            <p class="speaker">下駄</p>
            <p class="speech">わかりやすくはあるけどね。カゲヤマさんが書いた戯曲の価値をより多くの人に知ってもらうために、演出をして作品を作ってるんだっていうストーリーラインは。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">でもこういう演出をしたいみたいな欲望があんまりないんですよ。水をいっぱい降らせたいとか、でっかいものを出したいとか。そういう欲望はあんまりなくて、必要だからやるとか、スタッフさんと話してく中で生まれたらおもしろいねっていう感じなんだよね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そういう意味だと、今後子どもが生まれても戯曲を書くことの方が調整しやすいじゃない。だから、劇作家としてのオファーとかあるといいよね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">創作の仕事、あんまりなくて（笑）。</p>

            <p class="speaker">下駄</p>
            <p class="speech">シンポジウムとかキュレーションとか結構色々やってるから、周囲から見たときに何をしたい団体／人なのかがわかんないんだろうね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">創作の仕事もぜひ嬉しい。</p>

            <p class="speaker">下駄</p>
            <p class="speech">だからこの場で、カゲヤマ気象台は劇作家であるというパブリックイメージを作っていって依頼を待とうということだな。</p>
            <p class="speech">最後に一個だけ話したいんだけど、そういう諸々の状況を踏まえて、《乗る派》をこれからどうしていきたいなとかあるんですか。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">公演の規模感とかスパン的な話で言うと、次の吉祥寺シアターは1回で200人前後くらい動員できる劇場なんですけど、今後もその規模感でコンスタントに公演をやれる環境にしていかなきゃなとは思っていますね。今はもう、それ以外の選択肢があんまり魅力的に感じてないのもある。例えば小さい劇場でロングランをやるとか、野外劇場で上演するとか。</p>
            <p class="speech">今のこの集客感・認知度・規模感で演劇活動をやる上で、同じ悩みを考えてる人たちともっと話した方がいいんだろうな。同じような状況にある人で、今後の活動を考えた時に、選択肢が多いなと思えてる人って少ないような気がする。</p>

            <p class="speaker">下駄</p>
            <p class="speech">確かにね。《乗る派》は公演以外にもいろんな企画をやってもいるから、他の道筋もやろうとしてるんじゃないかと見えてるような気もするけどね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">まあね。でもある程度コンスタントに、このぐらいの規模感で公演が打てるっていうベースがあった上でやれることっていう気もする。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そのベースがあるからこそ、周縁の活動も周囲に対して意味付いていくってことだよね。それはそう思います。普通にただ戯曲を愚直にやりたいってなったら、劇場というものが適してたりするし。大きくなりたいという意思があるのであれば普通のことのような気もするよね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">とはいえ、いつまでもインディーズ精神は忘れずに行きたいっていうのはある。ある種の運動的なものとして活動をやってるという意識もあるので、売れたいみたいな気持ちももちろんあるけど、商業演劇のフリをするみたいなことはやりたくないな。</p>

            <p class="speaker">下駄</p>
            <p class="speech">インディーズなりの売れ方みたいなイメージがあればいいんだろうね。</p>
            <p class="speech">ぼくもメンバーだから、ぼくと《乗る派》の関係を考えていて。前にカゲヤマさんが「歴史に残ろうと思わないと演劇をやる意味ないんじゃないか」みたいなことを言っていて、すごいいい話だなと思った。演劇はめちゃくちゃお金が稼げる訳じゃないから、せっかくやるんだったら歴史に残りたいなって気持ちが僕にもある。それで具体的に考えた時に、俳優として歴史に名を轟かせるとしたらやっぱり売れなきゃダメだなと。社会に対して存在感を示していかないといけない。だからこのポッドキャストをやることには、ぼくの存在感を示していくという意味もあったりするわけ。もちろん売れたいんだったら、事務所に入ったりテレビにでた方がいいんじゃないかみたいな話もあるとは思うんだけど、現代演劇をやっているという自分の歴史性も大事にしたいんだよね。</p>
            <p class="speech">あとは、演劇界という社会全体から見ると特殊な場所で、特殊な活動をしているぼくが売れるには、ぼくが売れる環境をつくるみたいな方にも興味がある。つまり、演劇界を、ぼくが売れる場所に変えていくみたいなこと。そういう意識の中で、《乗る派》との関係を考えると、ぼくのプレゼンスが高まることは《乗る派》にとってもいいことだなと思ってるんだよね。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">いいじゃないですか。</p>

            <p class="speaker">下駄</p>
            <p class="speech">だから、現代演劇の俳優として売れる自分なりの道を見つけたいなと思っているし、それが演劇をやってる人の希望になったらもっと良いよなとも思っている。</p>

            <p class="speaker">カゲヤマ</p>
            <p class="speech">同じこと考えてる俳優さんはいっぱいいそうだけどね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">確かにね。売れ方について考える集まり、良さそう。でも結構珍しいらしいよ、現代演劇やっててめっちゃ売れたいと思ってるやつ（笑）。</p>
            <p class="speech">ぼくは演劇界のことをかなり考えちゃうんだけど、それも珍しいらしいし。でもこれを聞いてる人で興味がある人いたら話せたらいいですね。</p>
