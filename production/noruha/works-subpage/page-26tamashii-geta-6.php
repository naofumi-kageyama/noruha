                        <p class="speech">フランス語しゃべってたんですか？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そう、ボンジュールみたいな。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">ほかは？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">ボンソワーとか。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">「こんばんは」ですね</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">ありがとう、なんだっけ。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">「メルシー」ですね</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">すごい。もうフランス行けるね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">確かに。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">フランスはルーブル美術館とかもあるよ。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">三角形があるところですよね。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そうそう、建物が三角形で。モナリザを見たりとか。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">モナリザって意外と小さいって聞きます。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">厳重に管理されてるから、一番近くで見たとしても遠い。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">歴史感じました？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">ダヴィンチ。いいよね。こういうポーズの、、、</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">また手を平行に広げたポーズをとってます。あれですよね、手が上から下に連なってるやつ。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そうそう。あれとかすごいよね。解剖されちゃってる気持ちになりますよね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">あ、解剖されちゃったって思うんだ。共感してるんですね、</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">やっぱすごい人なんだなって思います。解剖図をみると、ただ書いてるだけじゃなくて、人体のことが含まれてるなと。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">ダヴィンチには結構いい印象があるんですね。</p>
                        <p class="speech">パリのお客さん、どんな感じだったんですか。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">パリのお客さんはすごい咀嚼してくれる感じだった。ドイツとはまた違う感じで。日本の作品はこんな感じか、みたいな。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">なるほど。これから僕が海外に行くこともあるかもしれないじゃないですか。なんか心構えとかあります？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">コンセントがみんな違う。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">それは海外旅行Tipsですよね。それは自分で別で調べられます。パスポートの取得は意外と時間がかかるから早めの申請がいいよとかじゃないんですよ。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そうだよね。でも海外に行くとご飯とかすごく美味しいのよ。フランスとかだと「タルタル」っていう料理があって。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">魚叩いたやつですか。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">あ、お肉の「タルタル」。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">生肉か。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そう。そういうのおいしくて食べちゃうんだけど、胃腸が弱い人だとあたっちゃうかもしれないから気をつけて。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">確かに。でも、そういうの食べないようにした方がいいんじゃないですか。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">やっぱ美味しいから食べたくなるよ。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">食べたくなって食べちゃうんだ。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">ワインとかも飲んじゃう。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">そういう料理ってお高いんじゃないですか？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">でも、1500円ぐらいだったかな。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">じゃあ、美味しいものが多いんだけど食べすぎて胃腸を壊さないように、ということが渡邊さんが俳優としてぼくに伝えたいことなんですね。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">身体が大事だからね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">僕、もっと演技のこととか聞きたいんですけど、</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">下駄さんは本当に素晴らしい俳優さんだから大丈夫。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">ありがとうございます。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">海外でもやっていけるよ。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">それはすごい勇気づけられますね。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">本当、お腹だけ気をつけて。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">お腹ですね。</p>
                        <p class="speech">一個気になったこととしては、上演を重ねる中で変わっていくみたいなことをどう捉えればいいんだろうと思っていて。《円盤に乗る派》は、初日から千秋楽まで同じ質のものを届けようみたいな思想があるんですね。お金をもらってるという意味でよくわかるなと思いつつ、海外でツアーとかすると期間も長くなるじゃないですか。長くなって変わらざるを得ないみたいなことをどう受け止めていけばいいんでしょう？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">もう、身を委ねる。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">身を委ねる。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">うん、もう大丈夫。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">自分の中で、これは変えないようにしないとな、とか思ったほうがいい部分とかないんですか？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そうね、セリフとか立ち位置とかそういう決まり事みたいなのは変えないという意思は持ってる。でも、下駄さんはすでにその意思をきっと持ってるから大丈夫。</p>
                        <p class="speech">あ、でもヨーロッパだと水が硬水だったりするから、喉痛めちゃったりするから気をつけて。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">硬水とお腹。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そうそう。あと、日本の食べ物が恋しくならないように、納豆とか持って行ったりするといいよ。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">税関で止められないですか、納豆。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">私は持っていったけど大丈夫だった。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">へー。お醤油とかも聞きますよね。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">パパットライス持っていって、味噌汁と納豆食べたときめっちゃおいしいと思えた。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">日本のご飯はやっぱり美味しい。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">美味しい。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">改めて日本のことを感じられるということですね。あの、特に演技とかに関してはアドバイスとかないですか？</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">大丈夫。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">そんなに大丈夫って言われるんだったら、きっと大丈夫なんだろうな。あとはチャンスを掴むだけってことですね。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そう、偶然と偶然が重なり合って。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">確かに。渡邊さんという歴史的な俳優になりたい仲間もできたのでうれしいです。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">運も訓練だからね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">掴みに行く練習をします。渡邊さんも、ぼくに合う仕事があったら紹介してください。オーディションには顔をボコボコにして行って、治ったときにいい顔だねって言われて受かったりします。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">そういえば、オーディションで写真を送ってくださいって言われた時に、一番自分らしい写真がいいかなと思ってプリクラを送ったことがあるんだけど落ちちゃったね。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">ぼくも制作的なことやるのでオーディション資料を見ることがあるんですけど。過去に映画のオーディションを手伝ってた時に、一人だけすごい解像度が低い写真送ってきた人がいて、逆に印象に残ってきてもらったらめちゃくちゃいい演技だったという話もあります。藤原竜也も、何回も落とされたけど、好きなスタッフさんが復活させたみたいな話も聞きますし。そういう運とか出会いも大事なんだなと思いますね。</p>
                        <p class="speech">話は尽きないところですが、そろそろお時間になりました。今回ゲストに来ていただきましたけど、どうでしたか。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">すごい充実していたと思います。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">充実してましたか。そう言っていただけて、聞いてくれる方も喜んでくれるかな。</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">大成功です。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">それでは皆様、また歴史の一ページでお会いしましょう。お相手は日和下駄と、</p>

                        <p class="speaker">渡邊</p>
                        <p class="speech">渡邊まな実でした。</p>

                        <p class="speaker">下駄</p>
                        <p class="speech">さようなら。</p>
