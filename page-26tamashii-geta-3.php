            <p class="speech">手法に現代を反映したものと、内容に現代を反映したものの二項があるとして、今はまさに内容に現代を反映したものとしてポリコレ的なものとかアイデンティティを問題にしたものが扱われているということは確かにすごくいいことだし、歴史は変わっていくんだということも感じる。</p>
            <p class="speech">一方で考えたいのが、現代を語るときに、「現代はやさしくない」みたいな話も同時にあるじゃない。戦争とか、近いところでは先の衆院選でお互いの意見を悪魔化するような対立がSNSで引き起こされたりもしてる。</p>
            <p class="speech">伊等くんは、ぶつかりあう人たちを描いている劇作家だなと思っているから、そのことについてはどう思ってるのか気になって。</p>

            <p class="speaker">伊等</p>
            <p class="speech">そうだよね（笑）</p>
            <p class="speech">今自分たちにとってリアリティのある言葉ってなんだろうって考えた時に、口語的な言葉ではないような気がしていて。なんて呼べばいいか分からないから普通のお芝居と言うけど、普通のお芝居で語られる口語っていうものに対して、確かに日常生活ではそうやって話しているんだけど、日常の言葉が写し取られて違和感がない話し方っていうことと、俺たちが「これが自分たちの社会だ」ってまさに思える言葉とで、いまの社会には差があると思ってる。</p>
            <p class="speech">なんでかというと、TwitterをはじめとしたSNSがあるからだよね。Twitterは、ちょっとした意見の食い違いとかポジションの違いがいわゆる「レスバ」に発展するような状況が生じてて、自分はそのことを書きたいと思ったのが、ひとつある。</p>
            <p class="speech">それから、これは自分の内的な話として、僕は母子家庭で、だいぶやんちゃな人間だったんでよく校長室に呼ばれて三者面談とかしてたんですけど。自分が子どもを生む可能性のある年齢、当時の母親と大体同じぐらいの年齢になって、一人で子供を育てて、それによっていかに差別を受けてきたかってことが身をもってわかるようになってきた。で、ここで自分が引き下がったら、例えば子供が悪いことになってしまう、ていうかそれだけじゃなくて、その差別がより加速するっていう不安もあったんじゃないかと思う。そういう状況で、自分の尊厳とか家族を守んなきゃいけない状況に置かれた時に出てくるような、反抗のための皮肉とか攻撃的な言葉を、ちゃんと書いた方がいいなと思った。それで『脱獄計画（仮）』と『想像の犠牲』を書いてみて、あらためてその大変さがリアリティとしてすごくわかってきた。今は「抵抗の言葉」をどうやって書くかっていうことが自分の課題。</p>
            <p class="speech">俺バスケやってたんだけど、ラシード・ウォーレスっていう選手がいてさ。審判にすぐ抗議するから、テクニカルファウルっていう、サッカーでいうイエローカードみたいな反則をすぐもらうんだよ。「歩くテクニカルファウル」って呼ばれてて。そういう人が好きなんだよ。「ちょっとおかしいじゃないですか！」って周りのこと気にせず言っちゃう人（笑）</p>

            <p class="speaker">下駄</p>
            <p class="speech">最初に話していた、SNSの台頭によってクラスタ化が進んでいる話から引き継ぐと、お互いが触れてくれるなと思っているという話は非常にそうだなと思う。時評の中で、「リーダブルな言葉を使って」ポリコレ的なものやアイデンティティの問題を扱ってると書いてあって。この「リーダブル」なものというのはみんなに伝わりやすいということだから、いいことではある一方、現実っていいことばかりじゃない。この現実の良くない部分を「リーダブル」な言葉で語るということは、みんなも見たくないんじゃないかという気がして。傷ついてしまうから。「リーダブル」な言葉を手法として扱うときに、人を傷つけない問題を扱わざるを得ないんだろうなという気がした。</p>

            <p class="speaker">伊等</p>
            <p class="speech">なるほどね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">伊等くんの作品は「リーダブル」な方法が使えない気がするんだよね。カゲヤマさんも「アンリーダブル」な方法を用いているなと思ってて、これも、人を傷つけないことだけを書いてるわけじゃないからだと思うんだよね。一方で「アンリーダブル」の方はわかりづらさがあるわけだから、おもしろさも提供できるように頑張っていかないといけないんだなと思った。</p>
            <p class="speech">《円盤に乗る派》の話でいうと、ぼくは自分が所属する団体だから《円盤に乗る派》の分析をたまにするんだけど、《円盤に乗る派》の特徴的な要素として、「内容」と「文体」と「演技」と「演出」があると思っている。4つあるのは多いと思うし、これが見る人のわかりづらさに繋がってる気がするんだよね。</p>
            <p class="speech">かなり前に鴻英良さんという方に、「君は革命を起こそうとは思わないのか」みたいなことを言われたという話があるんだけど、カゲヤマさんは革命を起こすタイプじゃないんだよね。でも同時によくないと思っている社会の状況もある。「内容」の話をすると、カゲヤマさんの戯曲には、全体が悪い方向に向かう流れがあったとして、逆行するんじゃなくて、ただ立って抵抗を感じるみたいな姿勢がある気がするんだよね。行動は起こさないんだけど、これをいいとは思ってないぞっていう。</p>
            <p class="speech">流れの抵抗を感じている自分の、まさにその現在性を扱っているなと思っていて、過去の戯曲とかは特に、人物がいてそれぞれが思ってることを言うみたいな形式になってる。この抵抗の仕方は、実は多くの人の実感に合ってるんじゃないのか。戦争に対して、よくないよなと思いながら、でも目の前のことをやらなきゃと思ってる、みたいなリアリティと近いというか。</p>

            <p class="speaker">伊等</p>
            <p class="speech">なるほど、確かにね。</p>
            <p class="speech">今回の《円盤に乗る派》の『「いまのところまだ存在しているわたしのたましいが……」』もそうだけど、カゲヤマさんは社会からこぼれ落ちてる、個人の寂しさみたいなのを書いてることが自分的にはすごく大事だなと思ってる。それが必ずしも、いまのわかりやすい抵抗みたいなものとは違うのかもしれないけど、絶対に大事なもので。たとえ連帯して密な状態になったり、あるいはお金持ちになって安泰な生活になったとしても、どこかで感じる個人の寂しさみたいなものを書き続けているように見える。《円盤に乗る派》の演劇は常に個の側についてるんだよね。それは今の社会状況と合わさって、よりクリティカルになってるなっていうのをすごい感じます。</p>

            <p class="speaker">下駄</p>
            <p class="speech">こぼれ落ちちゃう寂しさみたいなものを扱ってるという話は、「こぼれ落ちちゃう」人が多いということが問題なんだなと思う。多くの人ははっきりとした態度を取れない。でもはっきりした態度をとったほうが、面白い演劇になるというのもわかる。</p>

            <p class="speaker">伊等</p>
            <p class="speech">そうだね。おれの作品みたいな、バチバチになってる状態は出来事が起こってるから、演劇として見やすくはなるよね。自分の作品が見やすいかどうかはさておき（笑）。</p>

            <p class="speaker">下駄</p>
            <p class="speech">伊等くんの作品の世界観は、どちらかというと、人を傷つけることが前提になってるから、逆に出来事が飽和して、出来事が起こってないようにさえ見えるかもね。</p>

            <p class="speaker">伊等</p>
            <p class="speech">全員悪いやつだと思って書いてるんで、正論みたいなことを言わせてるなと思ったら、ちゃんとコイツの悪いこと書かないとなみたいな。あとはちょっとボケを入れたりもするね。自分が感じている正しさに浸らないで、そういうことを真面目に考えてる自分をどこかで哄笑う視線っていうのが必要なんだよね。</p>

            <p class="speaker">下駄</p>
            <p class="speech">アウトレイジみたいな外連味とかいるのかもね。</p>

            <p class="speaker">伊等</p>
            <p class="speech">でもアウトレイジ的な話とはちょっと違うんだよな。自分の実感では、基本的に今はみんな生きるのに必死すぎるんだよなっていうことを言いたい。アウトレイジは本当にヤクザだからさ（笑）。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そうか、暴力だからね。</p>

            <p class="speaker">伊等</p>
            <p class="speech">そうそう。例えば、ヨーロッパの劇場制度における、ブルジョア的な中産階級の人たちがいて、その人たちがどうやって市民意識を持つかみたいな話とも繋がっていて。その流れで劇場というものがあって、一方で現代のそういう人たちは演劇を見ているのかということも考えなきゃいけない。これからはどんどん格差が開いていくことも目に見えてる。そうなると、やっぱり生きるのが必死な人たちの言葉で、その人たちに向けて作ることが大事だなと思う。どんどん大きい話になってきてるけど、排外主義も、そういう考えを持つ人たちって、自分の生きているテリトリーが奪われてしまうんじゃないかという恐怖がデカいんじゃないかって気もするし。もちろん排外主義そのものに対する議論も必要なんだけど、そういう考えに導いてしまうような生活そのものの貧しさとかを考えないといけないと。</p>
            <p class="speech">自分はそう考えてるけど、《円盤に乗る派》はまた違う方法で、さっき言ったように社会からこぼれる人のことを考えている気がする。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そうだね。《円盤に乗る派》の回路で考えると、例えば、フェミニズム的な問題を扱う時に、そこからこぼれ落ちる人、例えば、自分もそうであるという実感を抱えながらだけど、男性のおじさんで貧乏みたいな人たちもたくさんいるじゃない。でも、男性性を持つ以上、その人たちは弱者ではないということになるみたいな時に、このこぼれ落ちてる人たちを扱おうみたいな演劇なのかもしれない。でもさっきいったように、このこぼれ落ちは「リーダブル」な方法では扱えない気がする。それで「アンリーダブル」な方法を使って難しい印象になってしまうと、前衛的な演劇を見る人は社会のごく一部だから、こぼれ落ちてる人に届けるということからさらに遠ざかってしまうということは難しい問題だなと思うな。</p>

            <p class="speaker">伊等</p>
            <p class="speech">そうだね、自分たちのニッチさみたいなもどかしさは常々ありますよね。その上でどう活動していくかと考えた時に、YouTubeとかTikTokとかやった方がいいのかとか思うよね（笑）。</p>

            <p class="speaker">下駄</p>
            <p class="speech">そうだね。みんなの実感に合わせなきゃいけないもんね。</p>
            <p class="speech">その状況の中で、ぼくが売れるということで、エンタメにも出るし難しい演劇にも出るという状態になって、下駄が出てるから見るという状況が作れたらいいんじゃないかという道を目指しているわけだ。</p>
          </section>

          <section>
            <h2 class="heading">文体から要請される演技態、「アンリーダブル」な文体にどう向かう？</h2>

            <p class="speaker">伊等</p>
            <p class="speech">先鋭的な演劇をつくる時に、コンセプチュアルにつくるかどうかという話は大きい気がするな。ぼくは戯曲を書くときに、設計図とかプロットを考えずに一文ずつ頭から書いていくという、小説家の保坂和志から影響を受けたスタイルをとっているので、いまのところコンセプトで作品全体を構造化するような作品を作ってこなかったけど。「アンリーダブル」な作品を、わかりやすく届ける時にコンセプトでパッケージするというのは一つの手だとは思う。</p>
            <p class="speech">去年の「秋の隕石」で『Signal to Noise』っていう海外招聘の作品を見たんだけど、あれはAIの言葉がスピーカーから流れてきて、人間がリップシンクするという、それ自体非常に強いコンセプトを持ってる。明確な物語もないし、言葉それ自体も意味が取れない部分があるという意味では「アンリーダブル」なんだけど、それでもまったく何やってるか分からないというふうにはならない。</p>

            <p class="speaker">下駄</p>
            <p class="speech">確かにそうだね。「リーダブル」かどうかは文体の話だから、演出とか演技とかの文体じゃない部分でどうできるかという話だよね。</p>

            <p class="speaker">伊等</p>
            <p class="speech">そうだね。演技の面でいうと、『想像の犠牲』を上演した時に、京都の初演ではすごく複雑な演劇を作ったなと自分自身感じてた。戯曲の構造がメタフィクションを重ねていくようなものだから、そういうものだと納得はしてたんだけど。ところが初演から5ヶ月後に東京公演をやったときに、俳優の戯曲の理解度と演技の解像度が爆上がりして、結果的に構造が何倍もクリアになった。俳優の凄さを見せつけられた瞬間で、それによってこの作品がどういうポテンシャルを持つ作品なのかに気づくことができた。その発見は『想像の犠牲』だけじゃなくて、今年以後制作する上での興味の指針にもなっている。</p>
            <p class="speech">ぼくの戯曲は文法が破綻してるし、映画とか小説のセリフを引用するためにかなり特殊な文体を使ってるから、一見読みづらい、上演しにくそうな戯曲なんだけど、俳優が上演した方がむしろわかりやすくなるということが起きた。</p>

            <p class="speaker">下駄</p>
            <p class="speech">いま聞いてて思ったんだけど、現代演劇における俳優の演技態って、文体から引き出されてる気がするね。</p>

            <p class="speaker">伊等</p>
            <p class="speech">その話は今回の《円盤に乗る派》もそうだよね。『仮想的な失調』からのカゲヤマさんの演劇観の更新みたいなのを結構感じる。</p>

            <p class="speaker">下駄</p>
            <p class="speech">感じるよね。文体の話でいうと『仮想的な失調』は、カゲヤマさんにとって一つのブレイクスルーだったかもしれない。カゲヤマさんの戯曲は意識の流れがそのまま書かれている、つまり頭の中で考えてることがそのまま書いてあるみたいな感じなんだけど、『仮想的な失調』でドラマが導入された。これまでドラマになりきらない日常を扱って、日常の雑多な意識を持った人たちが描かれていたと思うんだけど、ドラマが導入されたことで対立とか事件が起きるようになって、そういう人たちが事件を起こすにはどうしたらいいかみたいな書き方に変わっていった気がする。</p>
            <p class="speech">ただ、『仮想的な失調』の時は、直接的に誰かが誰かを傷つけるみたいな、個人間の争いはなかったというか、源平合戦を扱った能の演目『船弁慶』を下敷きにしてることもあるのかもしれないけど、Q太郎という主人公を刺しにくるヒラオカくんという人物は、亡霊であることが示唆されて少し抽象的な暴力として描かれてる。このように対立を書いているのは、これまでの書き方を踏まえている気がするな。</p>

            <p class="speaker">伊等</p>
            <p class="speech">確かに。同時にいま話した抽象的な暴力というか、目の前の人たちを動かしているここにはない何か、みたいなものも描かれてるよね。</p>
            <p class="speech">数日前に村上春樹を久しぶりに読んだら、寂しさみたいな部分も含めて、実は通底してるところがあるな気がして。社会のルールとか生活するうえでの他者とのつながりからこぼれ落ちてしまったところにある、寂寥感とか孤独があって、そこでは人とのつながりとか連帯が表面的なものにしか感じられない状態にありながら、都市で生きていくことの感触。この部分はカゲヤマさんの戯曲にも感じるんだよね。</p>
            <p class="speech">そういう、作品でカゲヤマさんが考えてることが稽古場の雰囲気にも浸透しているというか、一人一人が個人であって、全体的な雰囲気で押し流されないように稽古がシステム化されている。これは素直にすごいなと思った。リラックスした状態で俳優がちゃんとクリエイティビティを発揮できる稽古場っていうのは、なかなかないんじゃないかという気がしますね。おれは演出助手だけど、あまり気負わずに俳優に感想を話せるし、座組みのメンバーそれぞれの作品に対する取り組み方を尊重することがしっかりベースになってる。</p>

            <p class="speaker">下駄</p>
            <p class="speech">最近は演出も難しいなと思ってて。演出ってすごく人を縛る行為じゃない。基本的にはそうしたことは良くないとされている。でも何の統制もない状態で作られたものがおもしろいかというとそうは言い切れない部分も多い。根本的にはすごく暴力的かもしれない演出っていう作業だけど、カゲヤマさんのやり方は、ベースとなる思想を共有する中で、どうやったら俳優の自由が担保されるかみたいなことを考えてるやり方だなとは思うね。もちろん、思想を共有することも暴力性を持つとは思うから、演出が完璧に暴力的でなくなることは難しいとも思いつつ。</p>

            <p class="speaker">伊等</p>
            <p class="speech">そうね、自分もその部分は結構試行錯誤してる。イメージとかで決め切っちゃうのも、手放しすぎても良くないというか。だからこの現場でのカゲヤマさんのバランスによって生まれてる時間は作品に反映されつつあるなと稽古してて感じるので、きっと面白くなるんじゃないかな。</p>
