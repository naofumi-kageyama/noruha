            <h2 class="heading">コロナ禍を経た演劇界の状況、移り変わる技術と現代演劇が描くもの、そんな中で《円盤に乗る派》は何を描いている？</h2>

            <p class="speaker">伊等</p>
            <p class="speech">最初の「＃Me Too」は2015年頃で、そこからさらに5年経って、フェミニズムという言葉も少しずつ社会に浸透してくる中で、演劇界でも他人事ではないことが分かってきた。そして2020年にはコロナがあって、みんなが自分の身体のケアっていうことを真剣に考え始めた。そういう状況の中で、演劇が描く物語として”ケア”とか”フェミニズム”を扱ったものが出てきて、そして女性の作家がフィーチャーされていく流れがある。そのこと自体はめちゃくちゃいいことだと思ってるし、それこそさっき挙げた《円盤に乗る派》とかヌトミックとかの作品にもなかった視点だと思う。</p>
            <p class="speech">ただその上で、両方やろうよってことを言いたいんだけどね。実験的なことと、社会的におかしいところを指摘していくということを。</p>

